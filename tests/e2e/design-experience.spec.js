test('search suggestions work by keyboard and text navigation keeps native editing behavior', async ({ page }) => {
  await page.goto('/')
  const trigger = page.getByRole('button', { name: '打开搜索', exact: true })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: '搜索 RoadBook' })
  const suggestion = dialog.getByRole('button', { name: '赛里木湖', exact: true })
  await suggestion.focus()
  await page.keyboard.press('Enter')
  const input = dialog.getByRole('combobox')
  await expect(input).toHaveValue('赛里木湖')
  await expect(input).toBeFocused()
  await expect(dialog.getByRole('option').first()).toBeVisible()
  await page.keyboard.press('Home')
  expect(await input.evaluate((el) => el.selectionStart)).toBe(0)
  await page.keyboard.press('End')
  expect(await input.evaluate((el) => el.selectionStart)).toBe(4)
  await dialog.getByRole('button', { name: '清空搜索' }).click()
  await expect(input).toHaveValue('')
  await expect(input).toBeFocused()
  await input.fill('找不到的路书章节xyz')
  await expect(dialog.locator('.search-palette__empty')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(trigger).toBeFocused()
})

test('system dark mode covers search and printing while an explicit theme choice takes precedence', async ({ page, isMobile }) => {
  await page.emulateMedia({ colorScheme: 'dark', reducedMotion: 'reduce' })
  await page.goto('/')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByRole('button', { name: '打开搜索', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '搜索 RoadBook' })
  await expect(dialog).toBeVisible()
  const overlayBackground = await dialog.evaluate((el) => getComputedStyle(el).backgroundColor)
  expect(overlayBackground).not.toBe('rgb(255, 255, 255)')
  await page.keyboard.press('Escape')
  await page.goto(chapter(day5))
  await expect(page.locator('.chapter-content')).toBeVisible()
  const darkBackground = await page.locator('body').evaluate((el) => getComputedStyle(el).backgroundColor)
  await page.emulateMedia({ media: 'print' })
  await expect(page.locator('body')).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await expect(page.locator('.reader-toolbar')).toBeHidden()
  await expect(page.locator('.day-route-map-body')).toBeVisible()
  await page.emulateMedia({ media: 'screen' })
  await expect(page.locator('body')).toHaveCSS('background-color', darkBackground)
  const theme = isMobile ? page.getByRole('navigation', { name: '移动端快捷导航' }).getByRole('button', { name: '主题' }) : page.locator('.theme-toggle')
  await theme.click()
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
})

